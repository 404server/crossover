"""Writes web/data.js from every analysed environment: summaries (analyze.py) and autoscaling results
(analyze_hpa.py). Smoke tests are left out."""
import json
import pathlib


def write(root):
    load = lambda name: {f.parent.name: json.loads(f.read_text()) for f in sorted((root / "results").glob(f"*/{name}"))
                         if not f.parent.name.endswith("-smoke")}
    (root / "web").mkdir(exist_ok=True)
    (root / "web" / "data.js").write_text("// generated by analysis/webdata.py\nwindow.CROSSOVER = " + json.dumps(load("summary.json"))
                                         + ";\nwindow.CROSSOVER_HPA = " + json.dumps(load("hpa.json")) + ";\n")
